if (bannedEnvVars.length !== 51)
  throw new Error('expected 51 banned names, got ' + bannedEnvVars.length);

const ref = name => ({ $ref: '#/definitions/' + name });
// draft-07 ignores every keyword next to a $ref, so a ref that carries its own description or
// constraints goes in an allOf.
const withRef = (name, extra) => Object.assign({}, extra, { allOf: [ref(name)] });
// An optional key the reader takes with .S or SequenceOf may be left empty ('key:' or a value that is
// only a comment, e.g. repositoryCommit: #HASH#) - YAML makes that null, and the reader treats it as
// absent. So optional strings, lists and refs accept null too.
const str = description => ({ type: ['string', 'null'], description });
const list = (description, items, extra) => Object.assign({ type: ['array', 'null'], description, items }, extra);
const stringList = description => list(description, { type: 'string' });
const optRef = (name, extra) => Object.assign({}, extra, { anyOf: [{ type: 'null' }, ref(name)] });
const platformList = description => list(description, ref('platform'), { uniqueItems: true });

// TVersionRange.Parse: $version$, bundled, a bare version (exact pin, at least major.minor.patch), or a
// bracketed range that only floats the patch - [min,] [,max] or [min,max] with min and max on the same
// major.minor (\1 and \2 are the only capturing groups in the pattern).
function dependencyVersionPattern() {
  const rest = '(?:\\.[0-9]+)?(?:-[^+,\\])\\s]+)?(?:\\+[^,\\])\\s]+)?';
  const v = '[0-9]+\\.[0-9]+' + rest;
  const open = '[\\[(]\\s*';
  const close = '\\s*[\\])]';
  return '^\\s*(?:' + [
    ci('$version$'),
    ci('bundled'),
    '[0-9]+\\.[0-9]+\\.[0-9]+(?:-[^+]+)?(?:\\+.+)?',
    open + v + '\\s*,' + close,
    open + ',\\s*' + v + close,
    open + '([0-9]+)\\.([0-9]+)' + rest + '\\s*,\\s*\\1\\.\\2' + rest + close
  ].join('|') + ')\\s*$';
}

