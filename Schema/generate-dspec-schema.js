// Generates dspec-yaml-schema.json (next to this script) from the rules in Source/Core/Spec - the dspec
// reader. Edit this script and rerun it rather than editing the json:
//
//   node Schema/generate-dspec-schema.js [output file]
//
// Case-insensitive values are written as character-class patterns ([Ww][Ii][Nn]32) because JSON
// Schema regexes have no ignore-case flag. Node.js only - no packages needed.
const fs = require('fs');
