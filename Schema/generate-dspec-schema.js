const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const ci = s => esc(s).replace(/[A-Za-z]/g, c => '[' + c.toUpperCase() + c.toLowerCase() + ']');
const ciOneOf = list => '^\\s*(' + list.map(ci).join('|') + ')\\s*$';

